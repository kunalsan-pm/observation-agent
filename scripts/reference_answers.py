#!/usr/bin/env python
"""
Generate docs/EXPECTED_ANSWERS.md from live MCP tool calls.

Not agent output. This is the ground truth: each question in the built-in demo
set answered by calling the same tools the agent calls, straight from pandas,
with the tool invocation shown. It exists for three reasons —

  * a reader can see what the dataset actually contains without running anything;
  * it is the yardstick for judging an agent answer (the agent should reach
    these numbers, and `tests/test_detectors.py` pins the same values);
  * regenerating it after a change to a detector shows exactly what moved.

    python scripts/reference_answers.py
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "mcp_server"))
sys.path.insert(0, str(ROOT))

import analytics as A  # noqa: E402
import dataset as D  # noqa: E402
import queries as Q  # noqa: E402

from agent.questions import question_by_number  # noqa: E402

OUT = ROOT / "docs" / "EXPECTED_ANSWERS.md"
L: list[str] = []


def w(line: str = "") -> None:
    L.append(line)


def h(number: int) -> None:
    """Section header. Question text comes from agent/questions.py, so this
    document and the app can never show different wording."""
    spec = question_by_number(number)
    w(f"\n## Q{number} · {spec['group']} — {spec['short']}\n")
    w(f"> {spec['question']}\n")


def call(expr: str) -> None:
    w(f"**Tool call**\n\n```python\n{expr}\n```\n")


def table(headers: list[str], rows: list[list]) -> None:
    w("| " + " | ".join(headers) + " |")
    w("|" + "|".join(["---"] * len(headers)) + "|")
    for row in rows:
        w("| " + " | ".join("" if c is None else str(c) for c in row) + " |")
    w()


# ===========================================================================

w("# Expected answers")
w()
w(
    "Ground truth for the built-in demo questions, computed by calling the MCP "
    "server's own tools. Generated by `scripts/reference_answers.py` — regenerate "
    "after changing a detector to see exactly what moved."
)
w()
w(f"Data as of **{D.today_date()}**. Every relative window is measured from the end of that day.")
w()
w(
    "This is *not* agent output. It is the yardstick an agent answer should be "
    "judged against; `tests/test_detectors.py` pins the same numbers."
)

