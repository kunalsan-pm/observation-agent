"""
The one tool the agent has that is not read-only: writing a report to
``outputs/``.

Kept out of the MCP server on purpose — that server is honestly read-only, and
mixing a write tool into it would make that claim false. The write is confined
to ``outputs/`` by path containment rather than by trusting the model to
produce a well-behaved filename.
"""

from __future__ import annotations

import re
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parent.parent
OUTPUT_DIR = REPO_ROOT / "outputs"

WRITE_REPORT_TOOL: dict[str, Any] = {
    "name": "write_report",
    "description": (
        "Write a markdown report to outputs/. Required for every question you "
        "answer: the chat reply is a summary, this file is the durable artifact "
        "and must stand alone with the full answer, the method and definitions "
        "used, and citations (observation ids, associate ids, note ids, question "
        "ids). Call once per question, after the analysis is complete. Writing "
        "the same filename again replaces it."
    ),
    "input_schema": {
        "type": "object",
        "properties": {
            "filename": {
                "type": "string",
                "description": (
                    "Slug-style filename ending in .md, e.g. "
                    "'q07-critical-question-failures.md'. Written inside "
                    "outputs/; any directory component is stripped."
                ),
            },
            "title": {
                "type": "string",
                "description": "Report title, used as the H1 if the body lacks one.",
            },
            "markdown": {
                "type": "string",
                "description": (
                    "Full report body in markdown. Include Answer, Method, "
                    "Findings, Evidence and Caveats sections."
                ),
            },
        },
        "required": ["filename", "markdown"],
    },
}


def _safe_name(filename: str) -> str:
    """Reduce a model-supplied filename to a plain slug inside outputs/."""
    base = Path(str(filename or "report")).name
    base = re.sub(r"[^A-Za-z0-9._-]+", "-", base).strip("-._")
    if not base:
        base = "report"
    if not base.lower().endswith(".md"):
        base += ".md"
    return base[:120]


def write_report(filename: str, markdown: str, title: str | None = None) -> dict[str, Any]:
    """Write a report and return where it landed."""
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    name = _safe_name(filename)
    path = (OUTPUT_DIR / name).resolve()

    # Containment check: refuse anything that escapes outputs/, whatever the
    # model asked for.
    if OUTPUT_DIR.resolve() not in path.parents:
        return {"ok": False, "error": "refusing to write outside outputs/"}

    body = (markdown or "").strip()
    # Only an H1 counts as an existing title: a body that opens with "## Answer"
    # still needs one prepended.
    if title and not body.lstrip().startswith("# "):
        body = f"# {title}\n\n{body}"
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    body += (
        f"\n\n---\n*Generated by the Observation Agent · {stamp} · "
        "data as of 2026-05-12*\n"
    )

    existed = path.exists()
    path.write_text(body, encoding="utf-8")
    return {
        "ok": True,
        "path": f"outputs/{name}",
        "absolute_path": str(path),
        "bytes": len(body.encode()),
        "replaced_existing": existed,
    }


def list_reports() -> list[dict[str, Any]]:
    """Reports already on disk, newest first — for the UI's report panel."""
    if not OUTPUT_DIR.exists():
        return []
    out = []
    for p in OUTPUT_DIR.glob("*.md"):
        stat = p.stat()
        first_heading = None
        for line in p.read_text(encoding="utf-8", errors="replace").splitlines():
            if line.startswith("# "):
                first_heading = line[2:].strip()
                break
        out.append(
            {
                "path": f"outputs/{p.name}",
                "name": p.name,
                "title": first_heading or p.stem.replace("-", " ").title(),
                "bytes": stat.st_size,
                "modified": datetime.fromtimestamp(stat.st_mtime, timezone.utc).isoformat(),
            }
        )
    return sorted(out, key=lambda r: r["modified"], reverse=True)


def read_report(name: str) -> str | None:
    path = (OUTPUT_DIR / _safe_name(name)).resolve()
    if OUTPUT_DIR.resolve() not in path.parents or not path.exists():
        return None
    return path.read_text(encoding="utf-8", errors="replace")
