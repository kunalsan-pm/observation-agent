call("list_organizations()")
orgs = D.ORGS
w(f"**Three organizations**, covering three distinct industries.\n")
table(
    ["org_id", "Name", "Industry", "Projects", "Associates"],
    [
        [
            o["org_id"],
            o["name"],
            o["industry"],
            len([p for p in D.PROJECTS if p["org_id"] == o["org_id"]]),
            sum(1 for u in D.USERS if u["role"] == "associate" and u["org_id"] == o["org_id"]),
        ]
        for o in orgs
    ],
)

